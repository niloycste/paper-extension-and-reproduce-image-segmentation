
import csv
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RUNS = os.path.join(HERE, 'runs')
RESULTS = os.path.join(HERE, 'results')
os.makedirs(RESULTS, exist_ok=True)

# Frozen Step-1 baselines, for reference. Produced by the original (unmodified)
# train_polyp.py, 200 epochs, seed 42 -- see the Step-1 replication package.
FROZEN = [
    {'run': 'STEP1 baseline (original code)', 'dataset': 'ClinicDB', 'routing': 'fixed',
     'aux': False, 'epochs': 200, 'params': 27384, 'best_val': 0.8679,
     'test_dice': 0.9109, 'test_iou': 0.8463},
    {'run': 'STEP1 baseline (original code)', 'dataset': 'ColonDB', 'routing': 'fixed',
     'aux': False, 'epochs': 200, 'params': 27384, 'best_val': 0.7686,
     'test_dice': 0.7832, 'test_iou': 0.6946},
]

rows = []
for d in sorted(glob.glob(os.path.join(RUNS, '*'))):
    cfg_p = os.path.join(d, 'config.json')
    if not os.path.isfile(cfg_p):
        continue
    cfg = json.load(open(cfg_p))
    row = {'run': os.path.basename(d), 'dataset': cfg['dataset'],
           'routing': cfg['routing_mode'], 'aux': cfg['aux_supervision'],
           'kernels': ''.join(str(k) for k in cfg['kernel_sizes']),
           'epochs': cfg['epoch'], 'seed': cfg['seed'], 'params': cfg.get('params'),
           'init_from': os.path.basename(os.path.dirname(cfg['init_from']))
                        if cfg.get('init_from') else ''}

    res_p = os.path.join(d, 'result.json')
    if os.path.isfile(res_p):
        r = json.load(open(res_p))
        row.update(best_val=round(r['best_val_dice'], 4),
                   best_epoch=r['best_epoch'],
                   test_dice=round(r['test_dice_at_best_val'], 4),
                   train_h=round(r['train_time_s'] / 3600, 2))
    else:
        row['status'] = 'INCOMPLETE'

    for m in sorted(glob.glob(os.path.join(d, 'test_metrics_*.json'))):
        t = json.load(open(m))
        suffix = '_cross' if t.get('cross_dataset') else ''
        row[f'eval_dice{suffix}'] = round(t['dice'], 4)
        row[f'eval_iou{suffix}'] = round(t['iou'], 4)
        if t.get('routing'):
            row[f'select_frac{suffix}'] = str(t['routing']['select_frac'])
            row[f'routing_entropy{suffix}'] = t['routing']['entropy']

    for m in sorted(glob.glob(os.path.join(d, 'reliability_*.json'))):
        rel = json.load(open(m))
        if rel.get('cross_dataset'):
            continue
        row.update(ece=round(rel['ece'], 4), brier=round(rel['brier'], 4),
                   error_auroc=None if rel['error_auroc'] is None else round(rel['error_auroc'], 4))
    rows.append(row)

if not rows:
    print('no runs found in', RUNS)
    sys.exit(0)

cols = ['run', 'dataset', 'routing', 'aux', 'kernels', 'epochs', 'seed', 'params',
        'init_from', 'status', 'best_val', 'best_epoch', 'test_dice', 'train_h',
        'eval_dice', 'eval_iou', 'select_frac', 'routing_entropy',
        'eval_dice_cross', 'eval_iou_cross', 'ece', 'brier', 'error_auroc']

csv_path = os.path.join(RESULTS, 'all_runs.csv')
with open(csv_path, 'w', newline='', encoding='utf-8') as f:
    w = csv.DictWriter(f, fieldnames=cols, extrasaction='ignore')
    w.writeheader()
    for r in FROZEN + rows:
        w.writerow(r)

# Compact Markdown view of the columns that matter for the comparison
md = ['# Extension runs — collected results', '',
      'Generated by `path A/10_collect_results.py`. Blank cells mean the artefact does',
      'not exist yet, not that the value is zero. Runs at different epoch budgets are',
      'comparable only to runs at the same budget.', '',
      '| run | dataset | routing | aux | ep | params | best val | test DICE | eval DICE | ECE | err-AUROC |',
      '|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|']
for r in FROZEN + rows:
    md.append('| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |'.format(
        r.get('run', '')[:46], r.get('dataset', ''), r.get('routing', ''),
        r.get('aux', ''), r.get('epochs', ''), r.get('params', ''),
        r.get('best_val', ''), r.get('test_dice', ''), r.get('eval_dice', ''),
        r.get('ece', ''), r.get('error_auroc', '')))
print('\n'.join(md[5:]))
print(f'\nwrote {csv_path}')
